public class Customer {
    int age;
    String name;
    boolean isMale;
    boolean isVeg;
    String hobbies;

    // Constructor
    public Customer(String name, int age, boolean isMale, boolean isVeg, String hobbies) {
        this.name = name;
        this.age = age;
        this.isMale = isMale;
        this.isVeg = isVeg;
        this.hobbies = hobbies;
    }
}
