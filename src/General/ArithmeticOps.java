public class ArithmeticOps {
    public static void main(String[] args) {
        int a = 100;
        int b = 200;

        // + ops
        System.out.println("A + B = " + (a + b));
        // - ops
        System.out.println("A - B = " + (a - b));
        // / ops
        System.out.println("B / A = " + (b / a));
        // * ops
        System.out.println("B * A = " + (b * a));
        // % ops
        System.out.println("B % A = " + (b % a));
    }
}
