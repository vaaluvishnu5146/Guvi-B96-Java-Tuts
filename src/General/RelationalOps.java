public class RelationalOps {
    public static void main(String[] args) {
        int a = 50000;
        int b = 23000;

        int x = 1;
        int y = 1;

        System.out.println("A > B = " + (a > b)); // true
        System.out.println("A < B = " + (a < b)); // false
        System.out.println("A >= B = " + (a >= b)); // true
        System.out.println("A <= B = " + (a <= b)); // false
        System.out.println("X == Y = " + (x == y)); // true
        System.out.println("A != B = " + (a != b)); // true
    }
}
